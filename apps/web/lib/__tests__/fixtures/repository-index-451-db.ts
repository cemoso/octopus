import { mock } from "bun:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import { PgBoss } from "pg-boss";

const url = new URL(process.env.DATABASE_URL ?? "http://invalid");
assert.ok(["localhost", "127.0.0.1", "[::1]"].includes(url.hostname));
assert.match(url.pathname, /(^|[-_])test($|[-_])/);
mock.module("server-only", () => ({}));
const sentryEvents: Array<{ tags?: Record<string, string>; contexts?: { background_failure?: { retryCount?: number } } }> = [];
mock.module("@sentry/nextjs", () => ({ captureEvent: (event: typeof sentryEvents[number]) => { sentryEvents.push(event); return "e".repeat(32); } }));
const queued: unknown[] = [];
const logMessages: string[] = [];
mock.module("@/lib/queue", () => ({ enqueue: async (...args: unknown[]) => { queued.push(args); return "synthetic"; } }));
mock.module("@/lib/pubby", () => ({ pubby: { trigger: async () => {} } }));
mock.module("@/lib/elasticsearch", () => ({ writeSyncLog: ({ message }: { message: string }) => { logMessages.push(message); }, deleteSyncLogs: async () => {} }));
let calls = 0;
let fail = true;
const stats = { indexedFiles: 1, totalFiles: 1, totalChunks: 1, totalVectors: 1, contributors: [], contributorCount: 0, durationMs: 1 };
const { GitHubTreeRestrictedError, TREE_RESTRICTION_MESSAGE } = await import("@/lib/repository-tree-error");
const { safeIndexLogMessage } = await import("@/lib/index-log-safety");
mock.module("@/lib/indexer", () => ({ indexRepository: async () => { calls++; if (fail) throw new GitHubTreeRestrictedError(); return stats; } }));
const { prisma } = await import("@octopus/db");
const { enqueuePendingRepositoryIndexes, processRepositoryIndex } = await import("@/lib/repository-index-job");
const { runRepositoryIndex, SupersededIndexError, treeRestrictionEligible } = await import("@/lib/repository-index-completion");
const { reportBackgroundFailure } = await import("@/lib/background-failure");
const fixture = randomUUID();
const installationId = Number.parseInt(fixture.slice(0, 7), 16) + 1_000_000;
const org = await prisma.organization.create({ data: { name: "Synthetic", slug: `tree-451-${fixture}`, githubInstallationId: installationId, autoDiscoverRepos: true } });
const repo = await prisma.repository.create({ data: { organizationId: org.id, name: "fixture", fullName: "synthetic/fixture", externalId: fixture, installationId } });
const data = { organizationId: org.id, repositoryId: repo.id };
const queueSchema = `tree_queue_${fixture.replaceAll("-", "")}`;
const boss = new PgBoss({ connectionString: url.toString(), schema: queueSchema, pollingIntervalSeconds: 0.5 });
try {
  const migration = await readFile(new URL("../../../../../packages/db/prisma/migrations/20261107060000_index_tree_retry_after/migration.sql", import.meta.url), "utf8");
  await prisma.$transaction(async tx => {
    const schema = `tree_test_${fixture.replaceAll("-", "")}`;
    await tx.$executeRawUnsafe(`CREATE SCHEMA "${schema}"`);
    await tx.$executeRawUnsafe(`SET LOCAL search_path TO "${schema}"`);
    await tx.$executeRawUnsafe('CREATE TABLE repositories (id TEXT PRIMARY KEY, name TEXT NOT NULL)');
    await tx.$executeRawUnsafe("INSERT INTO repositories (id, name) VALUES ('old', 'preserved')");
    await tx.$executeRawUnsafe(migration);
    assert.deepEqual(await tx.$queryRawUnsafe('SELECT id, name, "indexRetryAfter" FROM repositories'), [{ id: "old", name: "preserved", indexRetryAfter: null }]);
    await tx.$executeRawUnsafe(`DROP SCHEMA "${schema}" CASCADE`);
  });
  await enqueuePendingRepositoryIndexes(org.id);
  assert.equal(queued.length, 1);
  await boss.start();
  await boss.createQueue("tree-451-test", { retryLimit: 2, retryDelay: 1 });
  let attempts = 0;
  await boss.work("tree-451-test", { includeMetadata: true, pollingIntervalSeconds: 0.5 }, async jobs => {
    for (const job of jobs) {
      attempts++;
      const retry = { retryCount: job.retryCount, retryLimit: job.retryLimit };
      try { await processRepositoryIndex(job.data as typeof data, retry); }
      catch (error) { reportBackgroundFailure(error, { stage: "indexing", attemptId: job.id, repositoryId: repo.id, retry }); throw error; }
    }
  });
  const jobId = await boss.send("tree-451-test", data);
  assert.ok(jobId);
  const deadline = Date.now() + 20_000;
  let job;
  do {
    await new Promise(resolve => setTimeout(resolve, 200));
    job = await boss.getJobById("tree-451-test", jobId);
  } while (job?.state !== "failed" && Date.now() < deadline);
  assert.equal(job?.state, "failed");
  assert.equal(attempts, 3);
  assert.equal(calls, 1, "retries must not repeat the GitHub call");
  assert.equal(sentryEvents.length, 1, "only the terminal retry should be reported");
  assert.equal(sentryEvents[0]?.tags?.failure_code, "http_451");
  assert.equal(sentryEvents[0]?.contexts?.background_failure?.retryCount, 2);
  assert.ok(logMessages.includes(TREE_RESTRICTION_MESSAGE));
  assert.equal(safeIndexLogMessage(TREE_RESTRICTION_MESSAGE), TREE_RESTRICTION_MESSAGE);
  let row = await prisma.repository.findUniqueOrThrow({ where: { id: repo.id } });
  assert.equal(row.indexStatus, "failed");
  assert.ok(row.indexRetryAfter && row.indexRetryAfter.getTime() > Date.now());
  queued.length = 0;
  await enqueuePendingRepositoryIndexes(org.id);
  assert.equal(queued.length, 0, "discovery must skip the cooldown");
  await prisma.repository.update({ where: { id: repo.id }, data: { indexRetryAfter: new Date(Date.now() - 1000) } });
  await enqueuePendingRepositoryIndexes(org.id);
  assert.equal(queued.length, 1, "discovery must resume after expiry");
  fail = false;
  await processRepositoryIndex(data);
  row = await prisma.repository.findUniqueOrThrow({ where: { id: repo.id } });
  assert.equal(row.indexStatus, "indexed");
  assert.equal(row.indexRetryAfter, null);
  const oldAttempt = randomUUID();
  const newerAttempt = randomUUID();
  const retained = new Date(Date.now() + 60_000);
  await prisma.repository.update({ where: { id: repo.id }, data: { indexStatus: "indexing", indexAttemptId: oldAttempt, indexRetryAfter: retained } });
  await assert.rejects(() => runRepositoryIndex(repo.id, oldAttempt, async () => {
    await prisma.repository.update({ where: { id: repo.id }, data: { indexAttemptId: newerAttempt } });
    throw new GitHubTreeRestrictedError();
  }), SupersededIndexError);
  row = await prisma.repository.findUniqueOrThrow({ where: { id: repo.id } });
  assert.equal(row.indexAttemptId, newerAttempt);
  assert.equal(row.indexStatus, "indexing");
  assert.equal(row.indexRetryAfter?.getTime(), retained.getTime(), "stale failures must not change a newer attempt's cooldown");
  await runRepositoryIndex(repo.id, newerAttempt, async () => stats, undefined, { deferTreeRestriction: true });
  row = await prisma.repository.findUniqueOrThrow({ where: { id: repo.id } });
  assert.equal(row.indexStatus, "indexed", "manual retry may run before cooldown expiry");
  assert.equal(row.indexRetryAfter, null);
  const manualAttempt = randomUUID();
  await prisma.repository.update({ where: { id: repo.id }, data: { indexStatus: "indexing", indexAttemptId: manualAttempt, indexRetryAfter: retained } });
  await assert.rejects(() => runRepositoryIndex(repo.id, manualAttempt, async () => { throw Object.assign(new Error("GitHub unavailable"), { status: 500 }); }, undefined, { deferTreeRestriction: true }), /GitHub unavailable/);
  row = await prisma.repository.findUniqueOrThrow({ where: { id: repo.id } });
  assert.equal(row.indexStatus, "failed");
  assert.equal(row.indexRetryAfter, null, "a different failure must not retain the restriction cooldown");
  const cancelAttempt = randomUUID();
  const controller = new AbortController();
  await prisma.repository.update({ where: { id: repo.id }, data: { indexStatus: "indexing", indexAttemptId: cancelAttempt, indexRetryAfter: retained } });
  await assert.rejects(() => runRepositoryIndex(repo.id, cancelAttempt, async () => { controller.abort(); throw new GitHubTreeRestrictedError(); }, controller.signal, { deferTreeRestriction: true }));
  row = await prisma.repository.findUniqueOrThrow({ where: { id: repo.id } });
  assert.equal(row.indexStatus, "pending");
  assert.equal(row.indexRetryAfter?.getTime(), retained.getTime(), "cancellation must preserve the restriction");
  queued.length = 0;
  await enqueuePendingRepositoryIndexes(org.id);
  assert.equal(queued.length, 0, "pending repositories must observe the restriction");
  for (const status of ["pending", "failed"]) {
    await prisma.repository.update({ where: { id: repo.id }, data: { indexStatus: status } });
    const claim = await prisma.repository.updateMany({ where: { id: repo.id, indexStatus: { notIn: ["indexed", "indexing"] }, ...treeRestrictionEligible(new Date()) }, data: { indexStatus: "indexing" } });
    assert.equal(claim.count, 0, `review claims must respect the restriction for ${status}`);
  }
  const externalAttempt = randomUUID();
  await prisma.repository.update({ where: { id: repo.id }, data: { indexStatus: "indexing", indexAttemptId: externalAttempt, indexRetryAfter: null } });
  await assert.rejects(() => runRepositoryIndex(repo.id, externalAttempt, async () => { throw new GitHubTreeRestrictedError(); }), GitHubTreeRestrictedError);
  row = await prisma.repository.findUniqueOrThrow({ where: { id: repo.id } });
  assert.equal(row.indexRetryAfter, null, "an unrelated credential must not defer installation-based discovery");
  await prisma.repository.update({ where: { id: repo.id }, data: { indexStatus: "indexing", indexAttemptId: externalAttempt, indexRetryAfter: retained } });
  await assert.rejects(() => runRepositoryIndex(repo.id, externalAttempt, async () => { throw new GitHubTreeRestrictedError(); }), GitHubTreeRestrictedError);
  row = await prisma.repository.findUniqueOrThrow({ where: { id: repo.id } });
  assert.equal(row.indexRetryAfter?.getTime(), retained.getTime(), "an unrelated credential must not extend an existing cooldown");
  await prisma.repository.update({ where: { id: repo.id }, data: { indexStatus: "indexing", indexAttemptId: externalAttempt } });
  await assert.rejects(() => runRepositoryIndex(repo.id, externalAttempt, async () => { throw new Error("unrelated failure"); }), /unrelated failure/);
  row = await prisma.repository.findUniqueOrThrow({ where: { id: repo.id } });
  assert.equal(row.indexRetryAfter?.getTime(), retained.getTime(), "an unrelated failure must preserve the cooldown");
  await prisma.repository.update({ where: { id: repo.id }, data: { indexStatus: "indexing", indexAttemptId: externalAttempt } });
  await runRepositoryIndex(repo.id, externalAttempt, async () => stats);
  row = await prisma.repository.findUniqueOrThrow({ where: { id: repo.id } });
  assert.equal(row.indexRetryAfter?.getTime(), retained.getTime(), "an unrelated success must preserve the cooldown");
  await prisma.repository.update({ where: { id: repo.id }, data: { provider: "forgejo", indexStatus: "failed", indexRetryAfter: retained } });
  queued.length = 0;
  await enqueuePendingRepositoryIndexes(org.id);
  assert.equal(queued.length, 1, "a GitHub cooldown must not suppress Forgejo discovery");
  const callsBeforeForgejo = calls;
  await processRepositoryIndex(data);
  assert.equal(calls, callsBeforeForgejo + 1);
  row = await prisma.repository.findUniqueOrThrow({ where: { id: repo.id } });
  assert.equal(row.indexStatus, "indexed");
  assert.equal(row.indexRetryAfter?.getTime(), retained.getTime());
  console.log("Synthetic PostgreSQL and pg-boss cooldown checks passed");
} finally {
  await boss.stop();
  await prisma.$executeRawUnsafe(`DROP SCHEMA IF EXISTS "${queueSchema}" CASCADE`);
  await prisma.organization.delete({ where: { id: org.id } });
  await prisma.$disconnect();
}
